package com.quentin.starassistws.restcotizar;

public class CrearPolizaResponse {

	private String codigoReserva;
	private String estadoReserva;
	private String estadoPago;
	private String error;
	private String mensajeReserva;
	private Integer idPoliza;
	private String correoReserva;
	
	public String getCodigoReserva() {
		return codigoReserva;
	}
	public void setCodigoReserva(String codigoReserva) {
		this.codigoReserva = codigoReserva;
	}
	public String getEstadoReserva() {
		return estadoReserva;
	}
	public void setEstadoReserva(String estadoReserva) {
		this.estadoReserva = estadoReserva;
	}
	public String getEstadoPago() {
		return estadoPago;
	}
	public void setEstadoPago(String estadoPago) {
		this.estadoPago = estadoPago;
	}
	public String getError() {
		return error;
	}
	public void setError(String error) {
		this.error = error;
	}
	public String getMensajeReserva() {
		return mensajeReserva;
	}
	public void setMensajeReserva(String mensajeReserva) {
		this.mensajeReserva = mensajeReserva;
	}
	public Integer getIdPoliza() {
		return idPoliza;
	}
	public void setIdPoliza(Integer idPoliza) {
		this.idPoliza = idPoliza;
	}
	public String getCorreoReserva() {
		return correoReserva;
	}
	public void setCorreoReserva(String correoReserva) {
		this.correoReserva = correoReserva;
	}
	
	
}
